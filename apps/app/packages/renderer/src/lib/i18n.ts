export type I18nKey = keyof typeof en;
type Table = Partial<Record<I18nKey, string>>;

/** The languages the app has words for: General › Language lists them. */
export const LANGUAGES: { id: string; name: string; table: Table }[] = [{ id: "en", name: "English", table: en }];

const tableFor = (lang: string): Table => LANGUAGES.find((l) => l.id === lang)?.table ?? en;

/** The words for `key` in `lang` (the user's language when not given), with `{name}`s filled. */
export function t(key: I18nKey, vars?: Record<string, string | number>, lang: string = preferences().language): string {
  let s: string = tableFor(lang)[key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** `t` for a component: it re-renders when the language changes. */
export function useT() {
  const lang = usePreference("language");
  return (key: I18nKey, vars?: Record<string, string | number>) => t(key, vars, lang);
}
